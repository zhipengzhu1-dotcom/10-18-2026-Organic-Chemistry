// Screen-reader pass of Unit 1 (#88). Plays every Unit 1 Lesson start to Wrap and reads each
// screen through the browser's accessibility tree, the same tree VoiceOver, NVDA and TalkBack read:
// every control and picture must have a name, and every Check must be announced in the live region.
// With SR_TRANSCRIPT=<file.md> it also writes the written transcript of what a screen reader meets
// (`pnpm sr:transcript` regenerates docs/qa/screen-reader-unit-1.transcript.md; the method and
// findings are in docs/qa/screen-reader-unit-1.md).
import { writeFileSync } from "node:fs";
import { expect, test } from "@playwright/test";
import { buildContent, contentRoot } from "@astratron/content";
import { playThrough } from "./site.ts";

const unit = buildContent(contentRoot).model!.subjects[0].courses[0].units[0];

/** Roles a screen reader can't use without a name. */
const UNNAMED = /^\s*- (img|button|slider|textbox|link|checkbox|radio|switch|application|dialog|region)( \[[^\]]*\])?:?$/;

test("a screen reader meets a name on every control and picture, and hears every Check, in every Unit 1 Lesson", async ({ page, browserName, browser }) => {
  test.setTimeout(600_000);
  const out: string[] = [
    "# Screen-reader transcript: Unit 1",
    "",
    `Generated by \`pnpm sr:transcript\` (site/e2e/screen-reader.spec.ts) on ${new Date().toISOString().slice(0, 10)} with ${browserName} ${browser.version()}, desktop size 1280 × 720.`,
    "Method: the browser's accessibility tree (what VoiceOver, NVDA and TalkBack read), not a live screen reader. See screen-reader-unit-1.md.",
    "Each Step lists the page in reading order as an ARIA tree, then what the live region announced after each Check.",
    "The Lessons are played the way the browser tests play them: the first choice, or 1, until each Step resolves.",
    "",
  ];
  const problems: string[] = [];
  for (const lesson of unit.lessons) {
    await page.goto("/");
    await page.evaluate(() => localStorage.clear());
    await page.goto(lesson.url);
    out.push(`## ${lesson.title}`, "", `Page title: "${await page.title()}"`, "");
    await playThrough(page, async (label) => {
      if (label.endsWith("feedback")) {
        const said = (await page.getByRole("status").innerText()).replace(/\s+/g, " ").trim();
        if (!said) problems.push(`${lesson.url} ${label}: Check announced nothing`);
        out.push(`Announced (live region): "${said}"`, "");
        return;
      }
      if (label === "results") return;
      // The Step as a screen reader's reading order meets it: the whole page (the player has no site chrome).
      const tree = await page.locator("body").ariaSnapshot();
      for (const line of tree.split("\n")) if (UNNAMED.test(line)) problems.push(`${lesson.url} ${label}: unnamed ${line.trim()}`);
      out.push(`### ${label}`, "", "```yaml", tree, "```", "");
    });
  }
  if (process.env.SR_TRANSCRIPT) writeFileSync(process.env.SR_TRANSCRIPT, out.join("\n"));
  expect(problems).toEqual([]);
});
