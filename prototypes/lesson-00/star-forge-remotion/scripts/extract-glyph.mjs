// One-off: pull the outline of "C" from JetBrains Mono Bold so the nucleus
// can morph into the real glyph. Writes src/glyph-c.ts (centred, 1 unit = 1 px at size 1000).
import opentype from 'opentype.js';
import {writeFileSync} from 'node:fs';
import {createRequire} from 'node:module';
const require = createRequire(import.meta.url);
const file = require.resolve('@fontsource/jetbrains-mono/files/jetbrains-mono-latin-700-normal.woff');
const font = opentype.loadSync(file);
const path = font.getPath('C', 0, 0, 1000);
const bb = path.getBoundingBox();
const cx = (bb.x1 + bb.x2) / 2, cy = (bb.y1 + bb.y2) / 2;
for (const c of path.commands) {
  for (const k of ['x', 'x1', 'x2']) if (k in c) c[k] -= cx;
  for (const k of ['y', 'y1', 'y2']) if (k in c) c[k] -= cy;
}
const d = path.toPathData(2);
const out = `// Generated by scripts/extract-glyph.mjs. JetBrains Mono Bold "C", font size 1000, centred on its bbox.
export const GLYPH_C = ${JSON.stringify(d)};
export const GLYPH_C_HEIGHT = ${(bb.y2 - bb.y1).toFixed(1)};
export const GLYPH_C_WIDTH = ${(bb.x2 - bb.x1).toFixed(1)};
`;
writeFileSync(new URL('../src/glyph-c.ts', import.meta.url), out);
console.log(out.slice(0, 300), '... contours:', (d.match(/M/g) || []).length);
