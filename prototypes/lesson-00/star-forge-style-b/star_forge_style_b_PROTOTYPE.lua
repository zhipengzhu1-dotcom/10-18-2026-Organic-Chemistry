-- PROTOTYPE (throwaway): star-forge Style B "Punchy Short" (9:16 first). Manim CE animation, edited, finished
-- and rendered by DaVinci Resolve (free 21.1.1) through this Lua script:
--   * timeline per aspect built natively (AppendToTimeline, record == source on one continuous Manim render)
--   * a 3-frame white flash on the fusion contact: Cross Dissolve in (2 f) and out (4 f) around a white clip
--   * Fusion finish on every Manim clip, identical everywhere so no cut or loop seam shows a look change:
--     MediaIn -> SoftGlow -> FilmGrain (MasterStrength) -> MediaOut
--   * no fade in (frame 0 is the best frame) and no fade out (the end loops into frame 0)
--   * three offline-mixed stems (music / fx / ui) on A1-A3 at unity
--   * H.264 + AAC renders, 1080x1920 and 1920x1080
--   * after the deliverables, a probe timeline: fusion transition "Brightness Flash", AudioVolume, audio SetFades
-- Run it ONLY through ../run-resolve-lua.sh (background AXPress, queued on a lock). Free 21.1 Lua has no io
-- library, so the report is raised as an error at the end and lands in ResolveDebug.txt between
-- STYLE_B_REPORT and STYLE_B_END. Plan block generated by make_style_b.py.

local ROOT = [[/Users/maracchi/Desktop/Claude/10. October 2026/10-18-2026 Organic Chemistry/wt-lesson00/prototypes/lesson-00]]
local EDIT = ROOT .. "/star-forge-style-b"
local OUT = EDIT .. "/out"
local PROBE = EDIT .. "/probe"
local SIZE = { ["16x9"] = {1920, 1080}, ["9x16"] = {1080, 1920} }
local ASPECTS = { "9x16", "16x9" }
local function srcPath(src, aspect) return EDIT .. "/media/" .. src .. "-" .. aspect .. ".mp4" end

-- BEGIN PLAN (generated by make_style_b.py)
local PLAN = {
  fps = 30, total = 360,
  clips = {
    { name = "hook-approach", src = "manim", s = 0, e = 90, rec = 0, finish = true },
    { name = "flash-white", src = "white", s = 12, e = 15, rec = 90, finish = false },
    { name = "fuse-to-card", src = "manim", s = 93, e = 342, rec = 93, finish = true },
    { name = "loop-dive", src = "manim", s = 342, e = 360, rec = 342, finish = true },
  },
  transitions = {  -- at the END of clip [after] (1-based), centred on the cut
    { after = 1, type = "Cross Dissolve", dur = 2 },
    { after = 2, type = "Cross Dissolve", dur = 4 },
  },
  finish = { glowThreshold = 0.62, glowGain = 0.5, grain = 0.06 },
  audio = {
    { stem = "music", track = 1 },
    { stem = "fx", track = 2 },
    { stem = "ui", track = 3 },
  },
}
-- END PLAN

local lines = {}
local function p(s) s = tostring(s); print(s); table.insert(lines, s) end
local function try(label, f, ...)
  local ok, r = pcall(f, ...)
  if not ok then p("  ! " .. label .. ": " .. tostring(r)); return nil end
  return r
end
local function wait(s) if bmd and bmd.wait then bmd.wait(s) end end

-- ------------------------------------------------------------------ Fusion finish
local loggedInputs = false
local function finish(item, tag)
  local comp = item:AddFusionComp()
  if not comp then p("  ! " .. tag .. ": AddFusionComp failed"); return end
  local a = comp:GetAttrs() or {}
  local mi, mo = comp:FindTool("MediaIn1"), comp:FindTool("MediaOut1")
  if not (mi and mo) then p("  ! " .. tag .. ": no MediaIn1/MediaOut1"); return end
  comp:Lock()   -- structural adds only; value writes happen unlocked (Lock + SetInput is not rendered)
  local glow = comp:AddTool("SoftGlow")
  local grain = comp:AddTool("FilmGrain")
  comp:Unlock()
  local msg = tag .. ": comp " .. tostring(a.COMPN_RenderStart) .. ".." .. tostring(a.COMPN_RenderEnd)
  local last = mi
  if glow then
    glow.Input = last.Output
    glow:SetInput("Threshold", PLAN.finish.glowThreshold)
    glow:SetInput("Gain", PLAN.finish.glowGain)
    last = glow
    msg = msg .. " SoftGlow(th=" .. tostring(glow:GetInput("Threshold")) .. ", gain=" .. tostring(glow:GetInput("Gain")) .. ")"
  else
    p("  ! " .. tag .. ": AddTool SoftGlow returned nil")
  end
  if grain then
    grain.Input = last.Output
    local okS = try("MasterStrength", function() return grain:SetInput("MasterStrength", PLAN.finish.grain) end)
    try("Monochrome", function() grain:SetInput("Monochrome", 1) end)
    try("MasterXSize", function() grain:SetInput("MasterXSize", 0.8) end)
    local rb = try("read MasterStrength", function() return grain:GetInput("MasterStrength") end)
    last = grain
    msg = msg .. " FilmGrain(MasterStrength set=" .. tostring(okS) .. " readback=" .. tostring(rb) .. ")"
  else
    p("  ! " .. tag .. ": AddTool FilmGrain returned nil")
  end
  mo.Input = last.Output
  p("  " .. msg)
end

local function readback(tl, t0, label)
  for _, kind in ipairs({ "video", "audio" }) do
    for k = 1, tl:GetTrackCount(kind) do
      local list = tl:GetItemListInTrack(kind, k) or {}
      local names = {}
      for _, x in ipairs(list) do table.insert(names, tostring(x:GetName()) .. "@" .. tostring(x:GetStart() - t0) .. "+" .. tostring(x:GetDuration())) end
      p("  " .. label .. " " .. kind .. k .. ": " .. #list .. " items: " .. table.concat(names, " | "))
    end
  end
end

-- ------------------------------------------------------------------ main
local APP = resolve or (Resolve and Resolve()) or (bmd and bmd.scriptapp and bmd.scriptapp("Resolve"))
local resolve, pm, proj, mp
local results = {}

local ok, err = pcall(function()
  resolve = APP
  assert(resolve, "no Resolve scripting handle")
  p("Resolve: " .. resolve:GetProductName() .. " " .. resolve:GetVersionString())
  pm = resolve:GetProjectManager()
  math.randomseed(os.time())
  local name = "star-forge-STYLE-B-" .. tostring(math.random(100000, 999999))
  proj = pm:CreateProject(name)
  assert(proj, "could not create project " .. name)
  p("project: " .. name)
  p("settings: fps=" .. tostring(proj:SetSetting("timelineFrameRate", "30")) ..
    " w=" .. tostring(proj:SetSetting("timelineResolutionWidth", "1080")) ..
    " h=" .. tostring(proj:SetSetting("timelineResolutionHeight", "1920")))
  mp = proj:GetMediaPool()

  local pool = {}
  local function import(key, path)
    local clips = mp:ImportMedia({ path })
    local c = clips and clips[1]
    if not c then p("  ! import FAILED: " .. path); return nil end
    pool[key] = c
    p("  imported " .. key .. ": frames=" .. tostring(c:GetClipProperty("Frames")) .. " fps=" .. tostring(c:GetClipProperty("FPS")) ..
      " res=" .. tostring(c:GetClipProperty("Resolution")))
    return c
  end
  p("import:")
  for _, a in ipairs(ASPECTS) do
    import("manim-" .. a, srcPath("manim", a))
    import("white-" .. a, srcPath("white", a))
  end
  for _, s in ipairs(PLAN.audio) do import(s.stem, EDIT .. "/audio/" .. s.stem .. ".wav") end

  -- endFrame: exclusive on 21.1.1 (cut-4 probe); re-probe anyway, it is cheap
  local endAdj = 0
  do
    local tl = mp:CreateEmptyTimeline("_probe-endframe")
    proj:SetCurrentTimeline(tl)
    local items = mp:AppendToTimeline({ { mediaPoolItem = pool["white-16x9"], startFrame = 0, endFrame = 10, mediaType = 1, trackIndex = 1, recordFrame = tl:GetStartFrame() } })
    local d = items and items[1] and items[1]:GetDuration()
    if d == 11 then endAdj = -1 end
    p("probe: endFrame 0..10 -> duration " .. tostring(d))
    mp:DeleteTimelines({ tl })
  end

  local function build(aspect)
    local w, h = SIZE[aspect][1], SIZE[aspect][2]
    local R = { transitions = 0, wanted = #PLAN.transitions, audio = 0 }
    results[aspect] = R
    p("== build " .. aspect)
    local tl = mp:CreateEmptyTimeline("star-forge STYLE B " .. aspect)
    assert(tl, "CreateEmptyTimeline failed")
    R.tl = tl
    proj:SetCurrentTimeline(tl)
    try("start tc", function() tl:SetStartTimecode("00:00:00:00") end)
    p("  custom=" .. tostring(tl:SetSetting("useCustomSettings", "1")) ..
      " w=" .. tostring(tl:SetSetting("timelineResolutionWidth", tostring(w))) ..
      " h=" .. tostring(tl:SetSetting("timelineResolutionHeight", tostring(h))))
    local t0 = tl:GetStartFrame()
    local items = {}
    for i, c in ipairs(PLAN.clips) do
      local got = mp:AppendToTimeline({ { mediaPoolItem = pool[c.src .. "-" .. aspect], startFrame = c.s, endFrame = c.e + endAdj,
        mediaType = 1, trackIndex = 1, recordFrame = t0 + c.rec } })
      local it = got and got[1]
      items[i] = it
      if it then
        local st, du = it:GetStart() - t0, it:GetDuration()
        p("  V1 " .. c.name .. ": rec " .. st .. " dur " .. du .. ((st == c.rec and du == c.e - c.s) and "" or "  ! expected rec " .. c.rec .. " dur " .. (c.e - c.s)))
      else
        p("  ! V1 " .. c.name .. ": AppendToTimeline returned nothing")
      end
    end
    for _, t in ipairs(PLAN.transitions) do
      local it = items[t.after]
      local tr = it and try("AddTransition", function()
        return it:AddTransition({ type = t.type, category = "simple", position = "end", alignment = "center", duration = t.dur })
      end)
      local label = PLAN.clips[t.after].name .. " -> " .. PLAN.clips[t.after + 1].name
      if tr then
        R.transitions = R.transitions + 1
        p("  T " .. label .. ": " .. tostring(try("tname", function() return tr:GetName() end)) .. " @" ..
          tostring(try("tstart", function() return tr:GetStart() - t0 end)) .. " dur " .. tostring(try("tdur", function() return tr:GetDuration() end)))
      else
        p("  ! T " .. label .. ": AddTransition returned nil")
      end
    end
    for i, c in ipairs(PLAN.clips) do
      if items[i] and c.finish then try("finish " .. c.name, finish, items[i], "F " .. c.name) end
    end
    while tl:GetTrackCount("audio") < #PLAN.audio do
      if not try("AddTrack", function() return tl:AddTrack("audio", "stereo") end) then break end
    end
    for _, s in ipairs(PLAN.audio) do
      local got = mp:AppendToTimeline({ { mediaPoolItem = pool[s.stem], startFrame = 0, endFrame = PLAN.total + endAdj,
        mediaType = 2, trackIndex = s.track, recordFrame = t0 } })
      local it = got and got[1]
      if it then R.audio = R.audio + 1; p("  A" .. s.track .. " " .. s.stem .. ": rec " .. (it:GetStart() - t0) .. " dur " .. it:GetDuration())
      else p("  ! A" .. s.track .. " " .. s.stem .. ": AppendToTimeline returned nothing") end
    end
    readback(tl, t0, "readback")
    p("  timeline end frame: " .. tostring(tl:GetEndFrame() - t0))
  end

  local function render(aspect, tl, dir, base)
    local w, h = SIZE[aspect][1], SIZE[aspect][2]
    proj:SetCurrentTimeline(tl)
    local fmt = proj:SetCurrentRenderFormatAndCodec("mp4", "H264")
    local set = proj:SetRenderSettings({ SelectAllFrames = true, TargetDir = dir, CustomName = base, FormatWidth = w, FormatHeight = h,
      FrameRate = 30, ExportVideo = true, ExportAudio = true, AudioCodec = "aac", AudioSampleRate = 48000 })
    p("  " .. base .. ": format/codec=" .. tostring(fmt) .. " settings=" .. tostring(set))
    local job = proj:AddRenderJob()
    if not job then p("  ! AddRenderJob failed for " .. base); return end
    proj:StartRendering(job)
    local guard = 0
    while proj:IsRenderingInProgress() and guard < 900 do wait(1); guard = guard + 1 end
    local st = proj:GetRenderJobStatus(job) or {}
    p("  " .. base .. ": " .. tostring(st.JobStatus) .. " " .. tostring(st.CompletionPercentage) .. "% " .. tostring(st.Error or ""))
    results["render-" .. base] = st.JobStatus
  end

  for _, a in ipairs(ASPECTS) do try("build " .. a, build, a) end
  pm:SaveProject()
  p("== render")
  for _, a in ipairs(ASPECTS) do
    local R = results[a]
    if R and R.tl then try("render " .. a, render, a, R.tl, OUT, "star-forge-style-b-" .. a) end
  end
  pm:SaveProject()

  -- ---- probes (not deliverables): new 21.1 calls on free, judged by the rendered file, not by readback
  p("== probe (16x9)")
  try("probe", function()
    local tl = mp:CreateEmptyTimeline("probe STYLE B")
    proj:SetCurrentTimeline(tl)
    tl:SetSetting("useCustomSettings", "1"); tl:SetSetting("timelineResolutionWidth", "1920"); tl:SetSetting("timelineResolutionHeight", "1080")
    local t0 = tl:GetStartFrame()
    local a = mp:AppendToTimeline({ { mediaPoolItem = pool["manim-16x9"], startFrame = 150, endFrame = 180 + endAdj, mediaType = 1, trackIndex = 1, recordFrame = t0 } })
    local b = mp:AppendToTimeline({ { mediaPoolItem = pool["manim-16x9"], startFrame = 180, endFrame = 210 + endAdj, mediaType = 1, trackIndex = 1, recordFrame = t0 + 30 } })
    local ia = a and a[1]
    local tr = ia and try("fusion transition", function()
      return ia:AddTransition({ type = "Brightness Flash", category = "fusion", position = "end", alignment = "center", duration = 12 })
    end)
    p("  fusion 'Brightness Flash': " .. (tr and (tostring(try("n", function() return tr:GetName() end)) .. " @" .. tostring(tr:GetStart() - t0) .. " dur " .. tostring(tr:GetDuration())) or "nil"))
    local au = mp:AppendToTimeline({ { mediaPoolItem = pool["music"], startFrame = 150, endFrame = 210 + endAdj, mediaType = 2, trackIndex = 1, recordFrame = t0 } })
    local ai = au and au[1]
    if ai then
      p("  AudioVolume before: " .. tostring(try("gv", function() return ai:GetProperty("AudioVolume") end)))
      p("  SetProperty AudioVolume -6: " .. tostring(try("sv", function() return ai:SetProperty("AudioVolume", -6) end)) ..
        " readback " .. tostring(try("gv2", function() return ai:GetProperty("AudioVolume") end)))
      p("  audio SetFades {FadeIn=15, FadeOut=15}: " .. tostring(try("af", function() return ai:SetFades({ FadeIn = 15, FadeOut = 15 }) end)))
      local f = try("gf", function() return ai:GetFades() end)
      if type(f) == "table" then p("  audio GetFades: in=" .. tostring(f.FadeIn) .. " out=" .. tostring(f.FadeOut)) end
    end
    readback(tl, t0, "probe")
    render("16x9", tl, PROBE, "probe-brightness-flash-audio-16x9")
  end)
  pm:SaveProject()
  p("done: " .. OUT)
end)
if not ok then p("ERROR: " .. tostring(err)) end
local summary = {}
for k, v in pairs(results) do
  if type(v) == "table" then table.insert(summary, k .. ": transitions " .. v.transitions .. "/" .. v.wanted .. ", audio " .. v.audio)
  else table.insert(summary, k .. ": " .. tostring(v)) end
end
table.sort(summary)
p("SUMMARY: " .. table.concat(summary, "; "))
error("STYLE_B_REPORT\n" .. table.concat(lines, "\n") .. "\nSTYLE_B_END", 0)
