local lines = {}
local function p(s) s = tostring(s); print(s); table.insert(lines, s) end
local function try(label, f, ...)
  local ok, r = pcall(f, ...)
  if not ok then p("  ! " .. label .. ": " .. tostring(r)); return nil end
  return r
end
local function wait(s) if bmd and bmd.wait then bmd.wait(s) end end

-- ------------------------------------------------------------------ Fusion finishing
local function key(tool, input, comp, pts)
  -- pts: { {frame, value}, ... }
  tool[input] = comp:BezierSpline({})
  for _, kv in ipairs(pts) do tool[input][kv[1]] = kv[2] end
end

local function inputNames(tool)
  local names = {}
  local ok = pcall(function()
    for _, inp in pairs(tool:GetInputList()) do
      local a = inp:GetAttrs(); table.insert(names, a.INPS_ID)
    end
  end)
  table.sort(names)
  return ok and table.concat(names, ",") or "?"
end

local loggedGrainInputs = false
-- extra: optional { lift = { {f,v},... } } for the BrightnessContrast fallback (dip to white / fades)
local function finish(item, tag, look, extra)
  local comp = item:AddFusionComp()
  if not comp then p("  " .. tag .. ": AddFusionComp failed, no finish on this clip"); return end
  local a = comp:GetAttrs() or {}
  local rs, re = a.COMPN_RenderStart or 0, a.COMPN_RenderEnd or 0
  local mi, mo = comp:FindTool("MediaIn1"), comp:FindTool("MediaOut1")
  if not (mi and mo) then p("  " .. tag .. ": no MediaIn1/MediaOut1, skipping"); return end
  -- structural adds under the lock only; every value write happens unlocked (Composition.Lock bug)
  comp:Lock()
  local glow = look and comp:AddTool("SoftGlow") or nil
  local grain = (look and look.grain) and comp:AddTool("FilmGrain") or nil
  local bc = (extra and (extra.lift or extra.gain)) and comp:AddTool("BrightnessContrast") or nil
  comp:Unlock()
  local last = mi
  local msg = tag .. ": comp range " .. tostring(rs) .. ".." .. tostring(re)
  if glow then
    glow.Input = last.Output
    glow:SetInput("Threshold", look.glowThreshold)
    glow:SetInput("Gain", look.glowGain)
    last = glow
    msg = msg .. " glow(th=" .. tostring(glow:GetInput("Threshold")) .. ",gain=" .. tostring(glow:GetInput("Gain")) .. ")"
  end
  if grain then
    grain.Input = last.Output
    if not loggedGrainInputs then p("  FilmGrain inputs: " .. inputNames(grain)); loggedGrainInputs = true end
    try("grain Strength", function() grain:SetInput("Strength", look.grain) end)
    try("grain LogProcessing", function() grain:SetInput("LogProcessing", 0) end)
    local raw = grain:GetInput("Strength")  -- returns nothing at all on some clips, and tonumber() rejects that
    local got = raw ~= nil and tonumber(raw) or nil
    if got == nil or math.abs(got - look.grain) > 1e-3 then
      -- never ship the default (heavy) grain: if the strength did not take, bypass the tool
      grain:SetAttrs({ TOOLB_PassThrough = true })
      msg = msg .. " grain BYPASSED (strength read back " .. tostring(got) .. ")"
    else
      last = grain
      msg = msg .. " grain(strength=" .. tostring(got) .. ")"
    end
  end
  if bc then
    bc.Input = last.Output
    if extra.lift then
      local pts = {}
      for _, kv in ipairs(extra.lift) do table.insert(pts, { rs + kv[1] + (kv[3] and (re - rs) or 0), kv[2] }) end
      key(bc, "Lift", comp, pts)
      msg = msg .. " lift-keys=" .. #pts
    end
    if extra.gain then
      local pts = {}
      for _, kv in ipairs(extra.gain) do table.insert(pts, { rs + kv[1] + (kv[3] and (re - rs) or 0), kv[2] }) end
      key(bc, "Gain", comp, pts)
      msg = msg .. " gain-keys=" .. #pts
    end
    last = bc
  end
  mo.Input = last.Output
  p("  " .. msg)
end

-- ------------------------------------------------------------------ main
-- the app handle, looked up before any local shadows the global names
local APP = resolve or (Resolve and Resolve()) or (bmd and bmd.scriptapp and bmd.scriptapp("Resolve"))
local resolve, pm, proj, mp
local results = {}

local ok, err = pcall(function()
  resolve = APP
  assert(resolve, "no Resolve scripting handle (resolve / Resolve() / bmd.scriptapp all nil)")
  p("Resolve: " .. resolve:GetProductName() .. " " .. resolve:GetVersionString())
  pm = resolve:GetProjectManager()
  try("edit page", function() resolve:OpenPage("edit") end)
  math.randomseed(os.time())
  local name = "star-forge-EDIT-PROTOTYPE-" .. tostring(math.random(100000, 999999))
  proj = pm:CreateProject(name)
  assert(proj, "could not create project " .. name .. " (is a modal dialog open, or an unsaved Untitled project current?)")
  p("project: " .. name)
  -- frame rate BEFORE any import: WAVs freeze the project rate at import time
  p("settings: fps=" .. tostring(proj:SetSetting("timelineFrameRate", "30")) ..
    " playback=" .. tostring(proj:SetSetting("timelinePlaybackFrameRate", "30")) ..
    " w=" .. tostring(proj:SetSetting("timelineResolutionWidth", "1920")) ..
    " h=" .. tostring(proj:SetSetting("timelineResolutionHeight", "1080")))
  mp = proj:GetMediaPool()

  -- ---- import every file on its own so a failure names its file
  local pool = {}
  local function import(keyName, path)
    local clips = mp:ImportMedia({ path })
    local c = clips and clips[1]
    if not c then p("  ! import FAILED: " .. path); return nil end
    pool[keyName] = c
    p("  imported " .. keyName .. ": frames=" .. tostring(c:GetClipProperty("Frames")) .. " fps=" .. tostring(c:GetClipProperty("FPS")) ..
      " res=" .. tostring(c:GetClipProperty("Resolution")))
    return c
  end
  p("import:")
  for _, a in ipairs(ASPECTS) do
    import("manim-" .. a, srcPath("manim", a))
    import("white-" .. a, srcPath("white", a))
  end
  for _, s in ipairs(PLAN.audio) do import(s.stem, EDIT .. "/audio/" .. s.stem .. ".wav") end
  import("mix", EDIT .. "/audio/mix.wav")

  -- ---- probe: is AppendToTimeline's endFrame inclusive or exclusive on this build?
  local endAdj = 0  -- added to (source out, exclusive) to get endFrame
  if pool["white-16x9"] then
    local tl = mp:CreateEmptyTimeline("_probe")
    proj:SetCurrentTimeline(tl)
    try("probe start tc", function() tl:SetStartTimecode("00:00:00:00") end)
    local items = mp:AppendToTimeline({ { mediaPoolItem = pool["white-16x9"], startFrame = 0, endFrame = 10, mediaType = 1, trackIndex = 1, recordFrame = tl:GetStartFrame() } })
    local d = items and items[1] and items[1]:GetDuration()
    if d == 11 then endAdj = -1 end
    p("probe: endFrame 0..10 gave duration " .. tostring(d) .. " -> endFrame is " .. (d == 11 and "INCLUSIVE" or "exclusive"))
    mp:DeleteTimelines({ tl })
  end

  -- ---- build one timeline per aspect
  local function build(aspect)
    local w, h = SIZE[aspect][1], SIZE[aspect][2]
    local R = { aspect = aspect, transitions = 0, transitionsWanted = #PLAN.transitions }
    results[aspect] = R
    p("== build " .. aspect)
    local tl = mp:CreateEmptyTimeline("star-forge EDIT " .. aspect)
    assert(tl, "CreateEmptyTimeline failed for " .. aspect)
    R.tl = tl
    proj:SetCurrentTimeline(tl)
    try("start tc", function() tl:SetStartTimecode("00:00:00:00") end)
    p("  custom=" .. tostring(tl:SetSetting("useCustomSettings", "1")) ..
      " w=" .. tostring(tl:SetSetting("timelineResolutionWidth", tostring(w))) ..
      " h=" .. tostring(tl:SetSetting("timelineResolutionHeight", tostring(h))) ..
      " start=" .. tostring(tl:GetStartFrame()))
    local t0 = tl:GetStartFrame()

    -- video
    local items = {}
    for i, c in ipairs(PLAN.clips) do
      local mpi = pool[c.src .. "-" .. aspect]
      local got = mpi and mp:AppendToTimeline({ { mediaPoolItem = mpi, startFrame = c.s, endFrame = c.e + endAdj,
        mediaType = 1, trackIndex = 1, recordFrame = t0 + c.rec } })
      local it = got and got[1]
      items[i] = it
      if it then
        local st, du = it:GetStart() - t0, it:GetDuration()
        local okPos = (st == c.rec and du == c.e - c.s)
        p("  V1 " .. c.name .. ": rec " .. st .. " dur " .. du .. (okPos and "" or ("  ! expected rec " .. c.rec .. " dur " .. (c.e - c.s))))
      else
        p("  ! V1 " .. c.name .. ": AppendToTimeline returned nothing")
      end
    end
    R.items = items

    -- transitions (native, 21.1)
    local failedDip = false
    for _, t in ipairs(PLAN.transitions) do
      local it = items[t.after]
      local tr = it and try("AddTransition", function()
        return it:AddTransition({ type = t.type, category = "simple", position = "end", alignment = "center", duration = t.dur })
      end)
      local label = PLAN.clips[t.after].name .. " -> " .. (PLAN.clips[t.after + 1] and PLAN.clips[t.after + 1].name or "?")
      if tr then
        R.transitions = R.transitions + 1
        p("  T " .. label .. ": " .. tostring(try("tname", function() return tr:GetName() end)) .. " @" ..
          tostring(try("tstart", function() return tr:GetStart() - t0 end)) .. " dur " .. tostring(try("tdur", function() return tr:GetDuration() end)))
      else
        p("  ! T " .. label .. ": AddTransition returned nil")
        if PLAN.clips[t.after].src == "white" or (PLAN.clips[t.after + 1] and PLAN.clips[t.after + 1].src == "white") then failedDip = true end
      end
    end

    -- fades: native SetFades (21.1); Fusion gain keys as the fallback
    local first, last = items[1], items[#items]
    local fadeInOk = first and try("SetFades in", function() return first:SetFades({ FadeIn = PLAN.fadeIn }) end)
    local fadeOutOk = last and try("SetFades out", function() return last:SetFades({ FadeOut = PLAN.fadeOut }) end)
    p("  fades: in=" .. tostring(fadeInOk) .. " out=" .. tostring(fadeOutOk))

    -- Fusion finishing per clip (+ fallbacks for anything native that failed)
    for i, c in ipairs(PLAN.clips) do
      local it = items[i]
      local look = c.finish and PLAN.finish[c.finish] or nil
      local extra = nil
      local n = c.e - c.s
      if i == 1 and not fadeInOk then extra = { gain = { {0, 0}, {PLAN.fadeIn, 1} } } end
      if i == #PLAN.clips and not fadeOutOk then extra = { gain = { {-PLAN.fadeOut, 1, true}, {0, 0, true} } } end
      if failedDip and PLAN.clips[i + 1] and PLAN.clips[i + 1].src == "white" then
        extra = extra or {}; extra.lift = { {n - 6, 0}, {n - 1, 1} }      -- ramp up to white into the white leg
      end
      if failedDip and PLAN.clips[i - 1] and PLAN.clips[i - 1].src == "white" then
        extra = extra or {}; extra.lift = { {0, 1}, {10, 0} }           -- and back down out of it
      end
      if it and (look or extra) then
        try("finish " .. c.name, finish, it, "  F " .. c.name, look, extra)
      end
    end

    -- audio: three stereo stems on A1-A3 (or the single mix on A1 if tracks cannot be added)
    local need = 0
    for _, s in ipairs(PLAN.audio) do if s.track > need then need = s.track end end
    local guard = 0
    while tl:GetTrackCount("audio") < need and guard < 4 do
      try("AddTrack", function() return tl:AddTrack("audio", "stereo") end); guard = guard + 1
    end
    local na = tl:GetTrackCount("audio")
    local subtypes = {}
    for k = 1, na do table.insert(subtypes, tostring(try("subtype", function() return tl:GetTrackSubType("audio", k) end))) end
    p("  audio tracks: " .. na .. " (" .. table.concat(subtypes, ",") .. ")")
    local placements = {}
    if na >= need then
      for _, s in ipairs(PLAN.audio) do table.insert(placements, { stem = s.stem, track = s.track }) end
    else
      table.insert(placements, { stem = "mix", track = 1 })
    end
    R.audio = 0
    for _, pl in ipairs(placements) do
      local mpi = pool[pl.stem]
      local got = mpi and mp:AppendToTimeline({ { mediaPoolItem = mpi, startFrame = 0, endFrame = PLAN.total + endAdj,
        mediaType = 2, trackIndex = pl.track, recordFrame = t0 } })
      local it = got and got[1]
      if it then
        R.audio = R.audio + 1
        p("  A" .. pl.track .. " " .. pl.stem .. ": rec " .. (it:GetStart() - t0) .. " dur " .. it:GetDuration())
      else
        p("  ! A" .. pl.track .. " " .. pl.stem .. ": AppendToTimeline returned nothing")
      end
    end
    -- a full readback of what is actually on the tracks
    for _, kind in ipairs({ "video", "audio" }) do
      for k = 1, tl:GetTrackCount(kind) do
        local list = tl:GetItemListInTrack(kind, k) or {}
        local names = {}
        for _, x in ipairs(list) do table.insert(names, tostring(x:GetName()) .. "@" .. tostring(x:GetStart() - t0) .. "+" .. tostring(x:GetDuration())) end
        p("  readback " .. kind .. k .. ": " .. #list .. " items: " .. table.concat(names, " | "))
      end
    end
    p("  timeline end frame: " .. tostring(tl:GetEndFrame() - t0))
  end

  local function render(aspect, tl, base)
    local w, h = SIZE[aspect][1], SIZE[aspect][2]
    proj:SetCurrentTimeline(tl)
    local fileName = base .. ".mp4"
    try("remove old", function() os.remove(OUT .. "/" .. fileName) end)
    local fmt = proj:SetCurrentRenderFormatAndCodec("mp4", "H264")
    local s = { SelectAllFrames = true, TargetDir = OUT, CustomName = base, FormatWidth = w, FormatHeight = h,
      FrameRate = 30, ExportVideo = true, ExportAudio = true, AudioCodec = "aac", AudioSampleRate = 48000 }
    local set = proj:SetRenderSettings(s)
    if not set then
      s.AudioCodec = nil; s.AudioSampleRate = nil; s.FrameRate = nil
      set = proj:SetRenderSettings(s)
      p("  render settings retry without AudioCodec/FrameRate: " .. tostring(set))
    end
    if not set then  -- the exact set that rendered in cut 3, plus audio
      set = proj:SetRenderSettings({ SelectAllFrames = true, TargetDir = OUT, CustomName = base,
        FormatWidth = w, FormatHeight = h, ExportAudio = true })
      p("  render settings minimal retry: " .. tostring(set))
    end
    p("  " .. base .. ": format/codec=" .. tostring(fmt) .. " settings=" .. tostring(set))
    local job = proj:AddRenderJob()
    if not job then p("  ! AddRenderJob failed for " .. base); return end
    proj:StartRendering(job)
    local guard = 0
    while proj:IsRenderingInProgress() and guard < 900 do wait(1); guard = guard + 1 end
    local st = proj:GetRenderJobStatus(job) or {}
    p("  " .. base .. ": " .. tostring(st.JobStatus) .. " " .. tostring(st.CompletionPercentage) .. "% " .. tostring(st.Error or ""))
    results["render-" .. base] = st.JobStatus
  end

  for _, a in ipairs(ASPECTS) do try("build " .. a, build, a) end
  pm:SaveProject()
  p("== render")
  -- 21.1 added Project.GetAudioRenderCodecs; its argument form is undocumented, so try a couple
  for _, arg in ipairs({ "mp4", "MP4" }) do
    local codecs = try("GetAudioRenderCodecs(" .. arg .. ")", function() return proj:GetAudioRenderCodecs(arg) end)
    if type(codecs) == "table" then
      for k, v in pairs(codecs) do p("  audio codec (" .. arg .. "): " .. tostring(k) .. " = " .. tostring(v)) end
      break
    end
  end
  for _, a in ipairs(ASPECTS) do
    local R = results[a]
    if R and R.tl then try("render " .. a, render, a, R.tl, "star-forge-edit-" .. a) end
  end
  pm:SaveProject()

  -- ---- diagnostic only (after the deliverables): does the FCPXML route import, and with what?
  p("== FCPXML diagnostic (16x9; not a deliverable)")
  try("fcpxml", function()
    local tl = mp:ImportTimelineFromFile(EDIT .. "/timeline/star-forge-16x9.fcpxml",
      { timelineName = "star-forge FCPXML 16x9", importSourceClips = true })
    if not tl then p("  ImportTimelineFromFile returned nil"); return end
    local t0 = tl:GetStartFrame()
    for _, kind in ipairs({ "video", "audio" }) do
      for k = 1, tl:GetTrackCount(kind) do
        local list = tl:GetItemListInTrack(kind, k) or {}
        local names = {}
        for _, x in ipairs(list) do table.insert(names, tostring(x:GetName()) .. "@" .. tostring(x:GetStart() - t0) .. "+" .. tostring(x:GetDuration())) end
        p("  fcpxml " .. kind .. k .. ": " .. #list .. " items: " .. table.concat(names, " | "))
      end
    end
    render("16x9", tl, "star-forge-edit-16x9-FCPXML-diagnostic")
  end)
  pm:SaveProject()
  p("done: " .. OUT)
end)
if not ok then p("ERROR: " .. tostring(err)) end
local summary = {}
for k, v in pairs(results) do
  if type(v) == "table" then
    table.insert(summary, k .. ": transitions " .. tostring(v.transitions) .. "/" .. tostring(v.transitionsWanted) .. ", audio clips " .. tostring(v.audio))
  else
    table.insert(summary, k .. ": " .. tostring(v))
  end
end
table.sort(summary)
p("SUMMARY: " .. table.concat(summary, "; "))
error("STAR_FORGE_EDIT_REPORT\n" .. table.concat(lines, "\n") .. "\nSTAR_FORGE_EDIT_END", 0)
