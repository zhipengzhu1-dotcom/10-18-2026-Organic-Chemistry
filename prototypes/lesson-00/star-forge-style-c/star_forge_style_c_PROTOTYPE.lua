local C = ROOT .. "/star-forge-style-c"
local OUT = C .. "/out"
local SIZE = { ["16x9"] = {1920, 1080}, ["9x16"] = {1080, 1920} }
local ASPECTS = { "16x9", "9x16" }

-- BEGIN PLAN (generated by make_style_c.py from timing.py; edit there)
local PLAN = {
  fps = 30, head = 21, total = 510, bar = 138,
  fadeIn = 36,  -- frames: the picture fades up from black under the rumble
  clips = {
    { name = "s1-star", s = 0, e = 60, rec = 21, look = "star" },
    { name = "s2-approach", s = 60, e = 156, rec = 81, look = "star" },
    { name = "s3-fuse", s = 156, e = 231, rec = 177, look = "fuse" },
    { name = "s4-pullback", s = 231, e = 324, rec = 252, look = "space" },
    { name = "s5-morph", s = 324, e = 375, rec = 345, look = "space" },
    { name = "s6-exit", s = 375, e = 381, rec = 396, look = "exit" },
    { name = "s7-card", s = 381, e = 489, rec = 402, look = "card" },
  },
  -- the fusion hit: Brightness Flash (pure-Fusion template), centred on the contact frame
  flash = { after = 2, type = "Brightness Flash", dur = 8 },
}
-- END PLAN

-- Finishing per look. flare = HotSpot PrimaryStrength keys {frame-in-clip, value} (negative frame = from the end)
local LOOK = {
  star  = { glowTh = 0.62, glowGain = 0.55 },
  fuse  = { glowTh = 0.60, glowGain = 0.50 },
  space = { glowTh = 0.50, glowGain = 0.50 },
  exit  = { glowTh = 0.50, glowGain = 0.50, blur = { {0, 0}, {-1, 14} } },
  card  = { glowTh = 0.50, glowGain = 0.45, blur = { {0, 14}, {4, 5}, {12, 0} } },
}
local FLARE = {
  ["s1-star"]     = { {0, 0.0}, {-1, 0.18} },
  ["s2-approach"] = { {0, 0.18}, {-22, 0.21}, {-1, 0.34} },   -- charges up under the hover
  ["s3-fuse"]     = { {0, 0.80}, {4, 0.50}, {14, 0.22}, {-1, 0.15} },  -- spikes on the hit, settles fast
  ["s4-pullback"] = { {0, 0.15}, {14, 0.0} },                  -- dies as the star starts to recede
}
local GRAIN = 0.015
local VIGNETTE_GAIN = 0.70

local lines = {}
local function p(s) s = tostring(s); print(s); table.insert(lines, s) end
local function try(label, f, ...)
  local ok, r = pcall(f, ...)
  if not ok then p("  ! " .. label .. ": " .. tostring(r)); return nil end
  return r
end
local function wait(s) if bmd and bmd.wait then bmd.wait(s) end end

local function setIn(tool, name, v, tag)
  local ok, r = pcall(function() return tool:SetInput(name, v) end)
  if not ok or r == false then p("  ! " .. tag .. " SetInput " .. name .. " -> " .. tostring(r)) end
end

-- keys: { {f, v}, ... } in clip frames (f < 0 counts from the clip's last frame); first visible frame = base
local function keyed(comp, tool, input, keys, base, last)
  tool[input] = comp:BezierSpline({})
  for _, kv in ipairs(keys) do
    local f = kv[1] >= 0 and (base + kv[1]) or (last + 1 + kv[1])
    tool[input][f] = kv[2]
  end
end

local function finish(item, clip, head, tail, aspect)
  local look = LOOK[clip.look]
  local comp = item:AddFusionComp()
  if not comp then p("  ! " .. clip.name .. ": AddFusionComp failed"); return end
  local a = comp:GetAttrs() or {}
  local rs, re = a.COMPN_RenderStart or 0, a.COMPN_RenderEnd or 0
  local base, last = rs + head, re - tail      -- first and last frame that are on screen
  local mi, mo = comp:FindTool("MediaIn1"), comp:FindTool("MediaOut1")
  if not (mi and mo) then p("  ! " .. clip.name .. ": no MediaIn1/MediaOut1"); return end
  local flare = FLARE[clip.name]
  -- structural adds under the lock only; every value write happens unlocked (Composition.Lock bug)
  comp:Lock()
  local hs = flare and comp:AddTool("HotSpot") or nil
  local st = flare and comp:AddTool("HotSpot") or nil
  local sg = comp:AddTool("SoftGlow")
  local cc = comp:AddTool("ColorCorrector")
  local fg = comp:AddTool("FilmGrain")
  local vb = comp:AddTool("BrightnessContrast")
  local em = comp:AddTool("EllipseMask")
  local bl = look.blur and comp:AddTool("Blur") or nil
  comp:Unlock()
  local tag = clip.name
  local chain = mi
  local msg = "  F " .. clip.name .. " [" .. rs .. ".." .. re .. " on-screen " .. base .. ".." .. last .. "]"
  if hs then
    -- the core flare: a hot white bloom on the star centre (the star sits at frame centre in s1-s4's start)
    hs.Input = chain.Output
    setIn(hs, "PrimaryCenter", { 0.5, 0.5 }, tag)
    setIn(hs, "HotSpotSize", 0.15, tag)
    setIn(hs, "LensAberration", 0, tag); setIn(hs, "Aberration", 0, tag)
    setIn(hs, "RadialOn", 0, tag); setIn(hs, "SecondaryStrength", 0, tag)
    keyed(comp, hs, "PrimaryStrength", flare, base, last)
    chain = hs
    -- the anamorphic streak: same centre, squashed aspect, weaker
    st.Input = chain.Output
    setIn(st, "PrimaryCenter", { 0.5, 0.5 }, tag)
    setIn(st, "HotSpotSize", 0.70, tag)
    setIn(st, "Aspect", 12, tag)  -- > 1 = horizontal (0.06 gave a vertical column in iteration 1)
    setIn(st, "LensAberration", 0, tag); setIn(st, "Aberration", 0, tag)
    setIn(st, "RadialOn", 0, tag); setIn(st, "SecondaryStrength", 0, tag)
    local sk = {}
    for _, kv in ipairs(flare) do table.insert(sk, { kv[1], kv[2] * 0.6 }) end
    keyed(comp, st, "PrimaryStrength", sk, base, last)
    chain = st
    msg = msg .. " flare(" .. #flare .. " keys)"
  end
  sg.Input = chain.Output
  setIn(sg, "Threshold", look.glowTh, tag); setIn(sg, "Gain", look.glowGain, tag)
  chain = sg
  -- technical first (a touch of contrast on the display-referred Manim render), then the creative lean:
  -- shadows a little cooler toward #0d0626, highlights a hair warmer; cyan/orange accents untouched in mids
  cc.Input = chain.Output
  setIn(cc, "MasterRGBContrast", 1.04, tag)
  setIn(cc, "ShadowsBlueGain", 1.06, tag); setIn(cc, "ShadowsRedGain", 0.97, tag)
  setIn(cc, "HighlightsRedGain", 1.02, tag)
  chain = cc
  fg.Input = chain.Output
  setIn(fg, "MasterStrength", GRAIN, tag)
  local gs = fg:GetInput("MasterStrength")
  chain = fg
  vb.Input = chain.Output
  setIn(vb, "Gain", VIGNETTE_GAIN, tag)
  setIn(em, "Invert", 1, tag); setIn(em, "SoftEdge", 0.45, tag)
  setIn(em, "Width", aspect == "16x9" and 1.15 or 1.25, tag); setIn(em, "Height", aspect == "16x9" and 1.15 or 1.25, tag)
  vb.EffectMask = em.Mask
  chain = vb
  if bl then
    bl.Input = chain.Output
    keyed(comp, bl, "XBlurSize", look.blur, base, last)
    chain = bl
    msg = msg .. " blur(" .. #look.blur .. " keys)"
  end
  mo.Input = chain.Output
  p(msg .. " glow " .. look.glowTh .. "/" .. look.glowGain .. " grain=" .. tostring(gs))
end

local APP = resolve or (Resolve and Resolve()) or (bmd and bmd.scriptapp and bmd.scriptapp("Resolve"))
local results = {}
local ok, err = pcall(function()
  local resolve = APP
  assert(resolve, "no Resolve scripting handle")
  p("Resolve: " .. resolve:GetProductName() .. " " .. resolve:GetVersionString())
  local pm = resolve:GetProjectManager()
  math.randomseed(os.time())
  local name = "star-forge-STYLE-C-" .. tostring(math.random(100000, 999999))
  local proj = pm:CreateProject(name)
  assert(proj, "could not create project " .. name)
  p("project: " .. name)
  p("settings fps=" .. tostring(proj:SetSetting("timelineFrameRate", "30")))
  local mp = proj:GetMediaPool()

  local function readback(tl, t0, tag)
    for _, kind in ipairs({ "video", "audio" }) do
      for k = 1, tl:GetTrackCount(kind) do
        local list = tl:GetItemListInTrack(kind, k) or {}
        local nm = {}
        for _, x in ipairs(list) do table.insert(nm, tostring(x:GetName()) .. "@" .. tostring(x:GetStart() - t0) .. "+" .. tostring(x:GetDuration())) end
        p("  " .. tag .. " " .. kind .. k .. ": " .. table.concat(nm, " | "))
      end
    end
  end

  local function build(aspect)
    local w, h = SIZE[aspect][1], SIZE[aspect][2]
    local R = { flash = false, bars = "n/a" }
    results[aspect] = R
    p("== build " .. aspect)
    proj:SetSetting("timelineResolutionWidth", tostring(w)); proj:SetSetting("timelineResolutionHeight", tostring(h))
    local tl = mp:ImportTimelineFromFile(C .. "/timeline/style-c-" .. aspect .. ".fcpxml",
      { timelineName = "star-forge STYLE-C " .. aspect, importSourceClips = true })
    assert(tl, "FCPXML import failed for " .. aspect)
    R.tl = tl
    proj:SetCurrentTimeline(tl)
    p("  custom=" .. tostring(tl:SetSetting("useCustomSettings", "1")) ..
      " w=" .. tostring(tl:SetSetting("timelineResolutionWidth", tostring(w))) ..
      " h=" .. tostring(tl:SetSetting("timelineResolutionHeight", tostring(h))) ..
      " readback " .. tostring(tl:GetSetting("timelineResolutionWidth")) .. "x" .. tostring(tl:GetSetting("timelineResolutionHeight")))
    local t0 = tl:GetStartFrame()
    -- V1: check every section landed where the plan says
    local v1 = tl:GetItemListInTrack("video", 1) or {}
    local items = {}
    for i, c in ipairs(PLAN.clips) do
      local it = v1[i]
      items[i] = it
      local st, du = it and (it:GetStart() - t0), it and it:GetDuration()
      if not it or st ~= c.rec or du ~= c.e - c.s then
        p("  ! V1 " .. c.name .. ": got rec " .. tostring(st) .. " dur " .. tostring(du) .. " expected " .. c.rec .. "+" .. (c.e - c.s))
      end
    end
    p("  V1: " .. #v1 .. " sections, first picture at " .. tostring(items[1] and (items[1]:GetStart() - t0)))
    -- the fusion hit: Brightness Flash centred on the contact frame
    local f = PLAN.flash
    local tr = try("flash", function()
      return items[f.after]:AddTransition({ type = f.type, category = "fusion", position = "end", alignment = "center", duration = f.dur })
    end)
    if tr then
      R.flash = true
      p("  T " .. tostring(tr:GetName()) .. " @" .. tostring(tr:GetStart() - t0) .. "+" .. tostring(tr:GetDuration()))
    else
      p("  ! Brightness Flash failed; trying Cross Dissolve so the cut still has a beat")
      try("xd", function() return items[f.after]:AddTransition({ type = "Cross Dissolve", category = "simple", position = "end", alignment = "center", duration = f.dur }) end)
    end
    p("  fade in " .. PLAN.fadeIn .. "f: " .. tostring(try("fades", function() return items[1]:SetFades({ FadeIn = PLAN.fadeIn }) end)))
    -- finishing per section; handles = half of each adjacent centred transition
    for i, c in ipairs(PLAN.clips) do
      local head = (i == f.after + 1) and f.dur / 2 or 0
      local tail = (i == f.after) and f.dur / 2 or 0
      if items[i] then try("finish " .. c.name, finish, items[i], c, head, tail, aspect) end
    end
    -- letterbox (16:9 only): crop the two black clips down to a 2.39:1 frame's bars
    if aspect == "16x9" then
      local top = (tl:GetItemListInTrack("video", 2) or {})[1]
      local bot = (tl:GetItemListInTrack("video", 3) or {})[1]
      if top and bot then
        local a1 = try("crop top", function() return top:SetProperty("CropBottom", h - PLAN.bar) end)
        local a2 = try("crop bottom", function() return bot:SetProperty("CropTop", h - PLAN.bar) end)
        local r1 = try("rb1", function() return top:GetProperty("CropBottom") end)
        local r2 = try("rb2", function() return bot:GetProperty("CropTop") end)
        R.bars = tostring(a1) .. "/" .. tostring(a2)
        p("  letterbox crops set " .. R.bars .. " readback " .. tostring(r1) .. "/" .. tostring(r2))
        if not (a1 and a2) then p("  ! letterbox crop refused") end
      else
        p("  ! letterbox clips missing on V2/V3 (video tracks: " .. tl:GetTrackCount("video") .. ")")
      end
    end
    readback(tl, t0, "rb")
    p("  timeline end " .. tostring(tl:GetEndFrame() - t0) .. " (plan " .. PLAN.total .. ")")
  end

  local function render(aspect)
    local R = results[aspect]
    local w, h = SIZE[aspect][1], SIZE[aspect][2]
    proj:SetCurrentTimeline(R.tl)
    local base = "star-forge-style-c-" .. aspect
    local fmt = proj:SetCurrentRenderFormatAndCodec("mp4", "H264")
    local set = proj:SetRenderSettings({ SelectAllFrames = true, TargetDir = OUT, CustomName = base,
      FormatWidth = w, FormatHeight = h, FrameRate = 30, ExportVideo = true, ExportAudio = true,
      AudioCodec = "aac", AudioSampleRate = 48000 })
    p("  render " .. base .. ": fmt=" .. tostring(fmt) .. " settings=" .. tostring(set))
    local job = proj:AddRenderJob()
    if not job then p("  ! AddRenderJob failed"); return end
    proj:StartRendering(job)
    local g = 0
    while proj:IsRenderingInProgress() and g < 900 do wait(1); g = g + 1 end
    local s = proj:GetRenderJobStatus(job) or {}
    p("  " .. base .. ": " .. tostring(s.JobStatus) .. " " .. tostring(s.CompletionPercentage) .. "% " .. tostring(s.Error or "") .. " (" .. g .. " s)")
    R.render = s.JobStatus
  end

  for _, a in ipairs(ASPECTS) do try("build " .. a, build, a) end
  pm:SaveProject()
  p("== render")
  for _, a in ipairs(ASPECTS) do if results[a] and results[a].tl then try("render " .. a, render, a) end end
  pm:SaveProject()
end)
if not ok then p("ERROR: " .. tostring(err)) end
local sum = {}
for k, v in pairs(results) do
  table.insert(sum, k .. ": flash=" .. tostring(v.flash) .. " bars=" .. tostring(v.bars) .. " render=" .. tostring(v.render))
end
table.sort(sum)
p("SUMMARY: " .. table.concat(sum, "; "))
error("STYLE_C_REPORT\n" .. table.concat(lines, "\n") .. "\nSTYLE_C_END", 0)
