-- PROTOTYPE (throwaway): star-forge, Style C "Cinematic Trailer". Manim CE animation, edited and finished in
-- DaVinci Resolve (free 21.1.1) by this Lua script. Run it via ../run-resolve-lua.sh (Workspace > Scripts).
-- What Resolve does here:
--   * timeline structure from an FCPXML (make_style_c.py): 0.7 s black head with the stems already running
--     (the J-cut), seven Manim sections on V1, letterbox bar clips on V2/V3 (16:9), three stems on A1-A3.
--     (FCPXML, not AddTrack: AddTrack("video") crashed free 21.1.1 in our probe.)
--   * native Brightness Flash transition (pure-Fusion template) centred on the fusion contact frame
--   * native fade up from black (SetFades)
--   * per-section Fusion finishing: HotSpot flare on the star (keyed: kindles, charges, spikes on the hit,
--     dies on the pull-back), SoftGlow, ColorCorrector (technical contrast + cooler shadows), FilmGrain
--     (MasterStrength), EllipseMask vignette, keyed Blur across the inverse zoom-through seam
--   * letterbox: Crop on the V2/V3 black clips, so the flash cannot brighten the bars
--   * H.264 + AAC renders in 16:9 and 9:16
-- Free 21.1 Lua has no io library: the report is raised as an error into ResolveDebug.txt between
-- STYLE_C_REPORT and STYLE_C_END. Lines starting "  !" are failures.

